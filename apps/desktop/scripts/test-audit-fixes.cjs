assert(renderer.includes("speechLanguage"),"speech language setting missing");
const docs=fs.readFileSync(path.join(root,"lib","documents.cjs"),"utf8");
assert(docs.includes("parseNumberCell"),"XLSX locale parser missing");
const mem=fs.readFileSync(path.join(root,"lib","memory.cjs"),"utf8");
assert(mem.includes("MAX_VECTORS = 5000")&&mem.includes("queryCache"),"embedding cache bound missing");
const store=fs.readFileSync(path.join(root,"lib","store.cjs"),"utf8");
assert(store.includes('path.join(dataDir, "conversations")'),"split conversation storage missing");
const extract=fs.readFileSync(path.join(root,"lib","extract.cjs"),"utf8");
assert(extract.includes("extractAccess")&&extract.includes('return "access"'),"Access support missing");
