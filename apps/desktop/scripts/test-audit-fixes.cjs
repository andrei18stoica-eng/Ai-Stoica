const assert=require("assert");
const fs=require("fs");
const path=require("path");
const root=path.join(__dirname,"..");
const gateway=fs.readFileSync(path.join(root,"local-gateway.cjs"),"utf8");
assert(!gateway.includes("RULARE COD REALĂ — executată local la cererea explicită a Owner-ului"),"chat must not auto-run fenced code");
assert(gateway.includes("validateAutomation"),"automation validation missing");
assert(gateway.includes("deepAllowed"),"deep research permission missing");
assert(gateway.includes('grant_type:"refresh_token"'),"OAuth refresh missing");
assert(gateway.includes("LIBRARY_REF"),"inline data URLs must be moved out of conversations");
assert(gateway.includes('app.post("/api/files"'),"binary /api/files upload missing");
